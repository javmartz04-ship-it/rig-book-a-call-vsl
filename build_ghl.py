#!/usr/bin/env python3
"""Builds the GoHighLevel loaders in ghl/*.js from the source pages.

Each GHL page in the "VSL Funnel" holds ONE line of custom code:
    <script src="https://javmartz04-ship-it.github.io/rig-book-a-call-vsl/ghl/<page>.js"></script>
The loader mounts the whole page (styles, markup, scripts) on top of the empty GHL page, so every
later edit is: change the source .html, run this script, push. Nothing is re-pasted in GHL.

Run:  python3 build_ghl.py
"""
import json, re, pathlib

ROOT = pathlib.Path(__file__).parent
BASE = 'https://javmartz04-ship-it.github.io/rig-book-a-call-vsl/'
BOOK_URL = '/consultation'          # step 2 of the GHL funnel (calendar)
PAGES = {                            # source file -> loader name
    'index.html': 'vsl',             # control: /opt-in-vsl
    'index-photo.html': 'photo',     # split-test variation
    'book.html': 'call',             # step 2: /consultation (calendar)
}


def absolutize(t):
    t = re.sub(r'''(["'(])assets/''', lambda m: m.group(1) + BASE + 'assets/', t)
    t = t.replace(', assets/', ', ' + BASE + 'assets/')     # srcset lists
    t = t.replace('`assets/', '`' + BASE + 'assets/')
    t = re.sub(r'src="survey\.js[^"]*"', 'src="%ssurvey.js?v=%d"' % (BASE, int((ROOT / 'survey.js').stat().st_mtime)), t)
    return t


def build(src, name):
    html = (ROOT / src).read_text()
    # the quiz sends finished applicants to the GHL calendar step
    html = html.replace('<script src="survey.js', "<script>window.BOOK_URL = '%s';</script>\n<script src=\"survey.js" % BOOK_URL, 1)
    # inline the booking page's stylesheet (the live GHL page has no book.css next to it)
    css = re.search(r'<link rel="stylesheet" href="book\.css[^"]*">', html)
    if css:
        html = html.replace(css.group(0), '<style>' + (ROOT / 'book.css').read_text() + '</style>')
    html = absolutize(html)
    head = re.search(r'<head>(.*?)</head>', html, re.S).group(1)
    body = re.search(r'<body[^>]*>(.*)</body>', html, re.S).group(1)
    title = re.search(r'<title>(.*?)</title>', head, re.S).group(1)

    scripts = []          # document order: head scripts first, then body scripts

    def take(m):
        attrs, code = m.group(1), m.group(2)
        srcm = re.search(r'src="([^"]+)"', attrs)
        if srcm:
            scripts.append({'src': srcm.group(1), 'attrs': dict(re.findall(r'(data-[a-z-]+)="([^"]*)"', attrs)), 'async': 'async' in attrs})
        else:
            scripts.append({'code': code})
        return ''
    head = re.sub(r'<script([^>]*)>(.*?)</script>', take, head, flags=re.S)
    body = re.sub(r'<script([^>]*)>(.*?)</script>', take, body, flags=re.S)
    head = re.sub(r'<title>.*?</title>|<meta charset[^>]*>|<meta name="viewport"[^>]*>', '', head, flags=re.S)

    blob = head + body + json.dumps(scripts)
    assert not re.search(r'''["'(`]assets/''', blob), src + ': relative asset left'
    assert 'book.html' not in body, src + ': link to book.html left'

    js = '''/* Generated by build_ghl.py from %s. Do not edit by hand. */
(function () {
  if (window.__rigvsl) return; window.__rigvsl = 1;
  var HEAD = %s, BODY = %s, SCRIPTS = %s, TITLE = %s;
  var d = document;
  d.title = TITLE;
  if (!d.querySelector('meta[name=viewport]')) { var m = d.createElement('meta'); m.name = 'viewport'; m.content = 'width=device-width,initial-scale=1'; d.head.appendChild(m); }
  // Hide the empty GHL page; our page is mounted straight on <body>.
  var hide = d.createElement('style');
  hide.textContent = 'body>*:not(#rigvsl):not(script):not(style):not(link){display:none!important}html,body{margin:0!important;padding:0!important}';
  d.head.appendChild(hide);
  d.head.insertAdjacentHTML('beforeend', HEAD);
  var root = d.createElement('div'); root.id = 'rigvsl'; root.innerHTML = BODY;
  // Body scripts run one after another, in order, so survey.js sees BOOK_URL and RIG_SOURCE.
  function run(i) {
    if (i >= SCRIPTS.length) return;
    var s = SCRIPTS[i], el = d.createElement('script');
    if (s.src) {
      el.src = s.src; for (var k in s.attrs) el.setAttribute(k, s.attrs[k]);
      if (s.async) { el.async = true; d.body.appendChild(el); run(i + 1); return; }
      el.onload = el.onerror = function () { run(i + 1); }; d.body.appendChild(el);
    } else { el.text = s.code; d.body.appendChild(el); run(i + 1); }
  }
  function mount() { d.body.appendChild(root); run(0); }
  if (d.body) mount(); else d.addEventListener('DOMContentLoaded', mount);
})();
''' % (src, json.dumps(head), json.dumps(body), json.dumps(scripts), json.dumps(title))
    js = js.replace('</script', '<\\/script')
    out = ROOT / 'ghl' / (name + '.js')
    out.parent.mkdir(exist_ok=True)
    out.write_text(js)
    print('%-17s -> ghl/%s.js  %d KB' % (src, name, len(js) // 1024))


for src, name in PAGES.items():
    build(src, name)
